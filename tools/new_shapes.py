# ---------------------------------------------------------------- checks
def positions(layers):
    out = []
    for z, rows in enumerate(layers):
        for r, line in enumerate(rows):
            for c, ch in enumerate(line):
                if ch not in ". ":
                    out.append((c, r, z))
    return out


def check():
    bad = 0
    for key, (display, layers) in S.items():
        problems = []
        pos = positions(layers)
        cells = set(pos)
        width = max(len(line) for rows in layers for line in rows)
        rows_n = max(len(rows) for rows in layers)
        if width > 8:
            problems.append("width %d" % width)
        if rows_n > 10:
            problems.append("rows %d" % rows_n)
        if len(pos) % 2:
            problems.append("odd count %d" % len(pos))
        if len(pos) < 24:
            problems.append("only %d tiles" % len(pos))
        for (c, r, z) in pos:
            if z > 0 and (c, r, z - 1) not in cells:
                problems.append("floating at %d,%d,%d" % (c, r, z))
        status = "OK " if not problems else "BAD"
        if problems:
            bad += 1
        print("%s %-16s %3d tiles  %d layers  %s" % (status, key, len(pos), len(layers), "; ".join(problems[:4])))
    print("%d shapes, %d with problems" % (len(S), bad))
    return bad


def emit():
    for key, (display, layers) in S.items():
        print('\t"%s": {' % key)
        print('\t\t"display": "%s",' % display)
        print('\t\t"layers": [')
        for rows in layers:
            print('\t\t\t"""')
            for line in rows:
                print(line)
            print('""",')
        print('\t\t],')
        print('\t},')


if __name__ == "__main__":
    if "--emit" in sys.argv:
        emit()
    else:
        sys.exit(1 if check() else 0)
